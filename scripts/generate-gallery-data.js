  'VW Crafter - Broown': 'VW Crafter 2026 — Marron',
  'VW Crafter - Red': 'VW Crafter 2026 — Rouge',
  'Renault Master - Model 1': 'Renault Master — Modèle 1',
  'Renault Master - Model 2': 'Renault Master — Modèle 2',
